// Draw one glyph at (x, y) with the given color (0 or 1). Returns the
// advance in pixels (always 5). Mirrors OledScreen::put_char_small except
// that we don't transpose axes — Move's set_pixel is (x, y) like normal.
export function putCharSmall(ch, x, y, color) {
    let code = typeof ch === 'string' ? ch.charCodeAt(0) : ch;
    if (code < 32) code = 32;
    if (code > 127) code = 127;
    code -= 32;
    const base = code * 5;
    for (let i = 0; i < 5; i++) {
        const col = FONT_SMALL[base + i];
        if (!col) continue;
        for (let j = 0; j < 8; j++) {
            if ((col >> j) & 1) set_pixel(x + i, y + j, color);
        }
    }
    return 5;
}

// Print a string at (x, y) using the small font, 1 px between glyphs.
export function printSmall(text, x, y, color) {
    let dx = x;
    for (let i = 0; i < text.length; i++) {
        dx += putCharSmall(text[i], dx, y, color);
        dx += 1;
    }
    return dx - x;   // total width drawn
}

// String pixel width (sum of 5+1 per char minus trailing gap).
export function textWidthSmall(text) {
    return text.length === 0 ? 0 : text.length * 6 - 1;
}
